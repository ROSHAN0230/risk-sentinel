"""
Risk Sentinel — Phase 2.7: PaySim Shortcut & Balance-Drain Analysis (Audit 6)
Audits:
1. Exact balance drain pattern (oldbalanceOrg == amount).
2. Transaction type exclusivity (fraud solely in TRANSFER / CASH_OUT).
3. Zero-balance accounts (is_orig_zero, is_dest_zero).
4. Taxonomy: Legitimate Causal Signals vs Synthetic Artifact Shortcuts.
"""

import os
import json
import numpy as np
import pandas as pd

def analyze_shortcuts(csv_path: str, output_dir: str) -> dict:
    os.makedirs(output_dir, exist_ok=True)
    print("==================================================")
    print("AUDIT 6: PAYSIM SHORTCUT & BALANCE-DRAIN ANALYSIS")
    print("==================================================")
    
    df = pd.read_csv(csv_path)
    n_rows = len(df)
    
    is_fraud = (df['isFraud'] == 1).to_numpy()
    non_fraud = ~is_fraud
    
    amounts = df['amount'].to_numpy()
    old_orig = df['oldbalanceOrg'].to_numpy()
    old_dest = df['oldbalanceDest'].to_numpy()
    tx_types = df['type'].to_numpy()
    
    # 1. Exact balance drain analysis: oldbalanceOrg == amount (or diff_orig_bal_amt == 0)
    is_exact_drain = np.isclose(old_orig, amounts, atol=1e-2)
    is_orig_zero = (old_orig == 0.0)
    is_dest_zero = (old_dest == 0.0)
    
    # Fraud exact drain rate
    fraud_exact_drain_cnt = int((is_fraud & is_exact_drain).sum())
    fraud_total_cnt = int(is_fraud.sum())
    fraud_exact_drain_pct = (fraud_exact_drain_cnt / fraud_total_cnt) * 100.0
    
    # Legitimate exact drain rate
    nonfraud_exact_drain_cnt = int((non_fraud & is_exact_drain).sum())
    nonfraud_total_cnt = int(non_fraud.sum())
    nonfraud_exact_drain_pct = (nonfraud_exact_drain_cnt / nonfraud_total_cnt) * 100.0
    
    # Precision of exact balance drain alone in TRANSFER / CASH_OUT
    is_transfer_or_cashout = np.isin(tx_types, ['TRANSFER', 'CASH_OUT'])
    drain_in_tc = is_exact_drain & is_transfer_or_cashout
    prec_exact_drain = int((is_fraud & drain_in_tc).sum()) / int(drain_in_tc.sum()) if drain_in_tc.sum() > 0 else 0.0
    
    # 2. Transaction type fraud distribution
    type_stats = {}
    for t in df['type'].unique():
        t_mask = (tx_types == t)
        t_fraud = int((is_fraud & t_mask).sum())
        t_total = int(t_mask.sum())
        type_stats[t] = {
            "total_transactions": t_total,
            "fraud_count": t_fraud,
            "fraud_prevalence_pct": (t_fraud / t_total) * 100.0 if t_total > 0 else 0.0
        }
        
    results = {
        "exact_balance_drain_forensics": {
            "fraud_transactions_exact_drain_count": fraud_exact_drain_cnt,
            "fraud_transactions_exact_drain_pct": fraud_exact_drain_pct,
            "nonfraud_transactions_exact_drain_count": nonfraud_exact_drain_cnt,
            "nonfraud_transactions_exact_drain_pct": nonfraud_exact_drain_pct,
            "precision_of_exact_drain_in_high_risk_channels": prec_exact_drain,
            "assessment": (
                f"{fraud_exact_drain_pct:.2f}% of all frauds in PaySim exhibit an exact 100% balance drain "
                f"(oldbalanceOrg == amount), compared to only {nonfraud_exact_drain_pct:.2f}% of legitimate transactions. "
                "This is a massive structural deterministic pattern generated by the PaySim multi-agent simulation."
            )
        },
        "transaction_type_exclusivity": {
            "distribution_by_type": type_stats,
            "zero_fraud_channel_volume": int((tx_types == 'CASH_IN').sum() + (tx_types == 'DEBIT').sum() + (tx_types == 'PAYMENT').sum()),
            "zero_fraud_channel_pct_of_dataset": ((tx_types == 'CASH_IN').sum() + (tx_types == 'DEBIT').sum() + (tx_types == 'PAYMENT').sum()) / n_rows * 100.0
        },
        "signal_taxonomy": {
            "legitimate_causal_signals": [
                "diff_orig_bal_amt (balance headroom at decision time)",
                "ratio_orig_bal_amt (proportion of total account wealth being transferred)",
                "oldbalanceOrg (raw liquidity context)",
                "hour_of_day / day_of_week (temporal velocity patterns)",
                "dest_prev_in_tx_cnt / dest_unique_orig_cnt (destination mule aggregation density)",
                "is_sender_cold_start / is_dest_cold_start (account maturity context)"
            ],
            "dataset_specific_synthetic_artifacts": [
                "100% absence of fraud in CASH_IN, DEBIT, and PAYMENT (3.59M records)",
                "Strict 100% liquidation drains (8,034 of 8,213 frauds drain exactly to 0.0)",
                "Complete absence of multi-step account takeovers or repeat sender fraud runs",
                "Fixed static step clock (1 hour per step up to 743 hours = 31 days)"
            ]
        }
    }
    
    out_file = os.path.join(output_dir, "shortcut_analysis.json")
    with open(out_file, 'w') as f:
        json.dump(results, f, indent=2)
        
    print(f"[+] Shortcut analysis complete. Saved to {out_file}")
    return results

